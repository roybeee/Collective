import assert from 'node:assert/strict';
import {testRuntime} from './helpers/runtime.mjs';
const {load}=testRuntime(async()=>{throw Error('No network');});
const {experimentStatistics,experimentDesignInput}=await load('lib/meta-experiment.ts');
let passed=0;const check=(v,label)=>{assert.ok(v,label);passed++;};
const design={metric:'paid_orders',minSample:100,minEffect:0.01,lowerBound:0,upperBound:1};
const values=(n,v)=>Array.from({length:n},()=>v);
check(experimentStatistics(design,values(100,0),values(100,1),1).status==='supported','clear benefit');
check(experimentStatistics(design,values(100,1),values(100,0),1).status==='rejected','clear harm');
check(experimentStatistics(design,values(100,0),values(100,0),1).status==='inconclusive','same results');
check(experimentStatistics(design,values(99,0),values(100,1),1).status==='insufficient','minimum per arm');
check(experimentStatistics(design,values(100,0),values(100,2),1).status==='invalid','no out-of-range clipping');
const a=experimentStatistics(design,values(100,0),values(100,1),1),b=experimentStatistics(design,values(100,0),values(100,1),2);
check(b.alpha<a.alpha&&b.interval[0]<a.interval[0],'correction consumes smaller alpha, not repeated fixed test');
check(JSON.stringify(a)===JSON.stringify(experimentStatistics(design,values(100,0),values(100,1),1)),'deterministic');
check(Math.abs(a.interval[0]-(1-2*Math.sqrt(Math.log(4/0.025)/200)))<1e-12,'two arms union bound reference value');
check(experimentStatistics({...design,metric:'contribution',lowerBound:-1000,upperBound:1000,minEffect:50},values(100,-900),values(100,900),1).status==='supported','continuous net contribution supported');
check(experimentStatistics(design,values(100,NaN),values(100,1),1).status==='invalid','nonfinite invalid');
for(const bad of [{minEffect:-1},{minEffect:2},{lowerBound:1},{assignmentUnit:'email'}])assert.throws(()=>experimentDesignInput({minEffect:0.01,lowerBound:0,upperBound:1,assignmentUnit:'pseudonymous_visitor',taxBasis:'net_tax_explicit',...bad},'paid_orders'));
passed+=4;
console.log(JSON.stringify({passed}));
