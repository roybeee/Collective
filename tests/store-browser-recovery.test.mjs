import assert from 'node:assert/strict';
import {testRuntime} from './helpers/runtime.mjs';
const {load,sql}=testRuntime(async()=>{throw Error('No external calls')});
const s=await load('lib/server.ts'),m=await load('lib/store-browser-server.ts');
const owner='browser-recovery',who={id:owner,role:'owner'};
const action=input=>m.storeBrowserAction(owner,input,who);
await s.recordStatement(owner,'store','store',{id:'store',name:'Fixture',status:'active'}).run();
await s.recordStatement(owner,'feature_flag','store_browser_execution',{enabled:true}).run();
const {device,token}=await action({action:'register_device',label:'Fixture',profileId:'u0'});
const auth=await m.authenticateBrowserWorker(new Request('https://local.test',{headers:{authorization:'Bearer '+token}}));
await action({action:'save_binding',storeId:'store',deviceId:device.id,profileId:'u0',naverPlaceId:'1',managerBusinessId:'2',managerUrl:'https://new.smartplace.naver.com/observed'});
const valid=(await action({action:'create_job',storeId:'store',type:'read_hours'})).job;
const draft=(await action({action:'create_job',storeId:'store',type:'change_hours',beforeHours:'10–18',afterHours:'10–19'})).job;
const expired=(await action({action:'approve_job',jobId:draft.id,expectedVersion:draft.version})).job;
await s.recordStatement(owner,'store_browser_job',expired.id,{...expired,approvedUntil:new Date(Date.now()-1000).toISOString()},'store').run();
sql.prepare("UPDATE records SET updated_at='9999' WHERE owner=? AND kind='store_browser_job' AND id=?").run(owner,`${owner}:store_browser_job:${expired.id}`);
const claim=await m.browserWorkerAction(auth,{action:'claim'});
assert.equal(claim.job.id,valid.id,'expired queued write must not starve valid read');
console.log(JSON.stringify({passed:1,evidence:'mocked auth, real memory SQL, external calls zero'}));
